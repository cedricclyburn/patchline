import type { Check, CheckName, DependencyChange, Finding, GateDecision, ReviewVerdict, StampedEvent, TriageVerdict } from "./domain.ts";

/** Everything a PR body needs, folded from the ledger. */
export interface RemediationView {
  findings: Finding[];
  verdicts: TriageVerdict[];
  checks: Map<CheckName, Check>;
  changes: DependencyChange[];
  diffStat: string;
  review: ReviewVerdict | null;
  decision: GateDecision | null;
  summary: string;
  models: Map<string, string>;
}

export const CHECK_LABELS: Record<CheckName, string> = {
  policy: "Policy file parsed",
  baseline_tests: "Baseline tests (before patch)",
  patched_tests: "Tests after patch",
  targeted_vulns_cleared: "Targeted vulnerabilities cleared on rescan",
  no_new_vulns: "No new vulnerabilities introduced",
  test_count_not_reduced: "Test count not reduced",
  diff_scope: "Diff touches only allowed files",
  independent_review: "Independent model review",
};

export function fold(events: StampedEvent[]): RemediationView {
  const v: RemediationView = {
    findings: [], verdicts: [], checks: new Map(), changes: [], diffStat: "",
    review: null, decision: null, summary: "", models: new Map(),
  };
  for (const e of events) {
    switch (e.type) {
      case "findings": v.findings = e.findings; break;
      case "triage": v.verdicts = e.verdicts; break;
      case "check": v.checks.set(e.check.name, e.check); break;
      case "changes": v.changes = e.changes; v.diffStat = e.diffStat; break;
      case "review": v.review = e.review; break;
      case "gate": v.decision = e.decision; break;
      case "agent_done":
        v.models.set(e.role, e.model);
        if (e.role === "remediate") v.summary = e.summary;
        break;
      default: break;
    }
  }
  return v;
}

const ICON: Record<Check["state"], string> = { pass: "✅", fail: "❌", warn: "⚠️", pending: "⏳", skipped: "➖" };
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderPrBody(view: RemediationView, ctx: { repo: string; riskClass: string; incidentUrl: string | null }): string {
  const verdictFor = new Map(view.verdicts.map((t) => [t.id, t]));
  const findings = view.findings
    .map((f) => {
      const t = verdictFor.get(f.id);
      const vex = t ? `${t.status}${t.justification ? ` (${t.justification})` : ""}` : "not triaged";
      return `| ${f.id} | ${f.pkg} | ${f.installed} → ${f.fixed ?? "no fix"} | ${f.severity}${f.cvss ? ` ${f.cvss}` : " (not scored)"} | ${cell(vex)} |`;
    })
    .join("\n");

  const checks = (Object.keys(CHECK_LABELS) as CheckName[])
    .map((name) => {
      const c = view.checks.get(name) ?? { name, state: "pending" as const, detail: "not yet measured" };
      return `| ${ICON[c.state]} | ${CHECK_LABELS[name]} | ${cell(c.detail)} |`;
    })
    .join("\n");

  const changes = view.changes.map((c) => `- \`${c.pkg}\` ${c.from} → ${c.to}${c.major ? " **(major)**" : ""}`).join("\n") || "- none";
  const decision = view.decision
    ? `**${view.decision.kind}**\n\n${view.decision.reasons.map((r) => `- ${r}`).join("\n")}`
    : "pending";
  const review = view.review ? `**${view.review.verdict}** (${view.review.model})\n\n${view.review.notes}` : "not run";

  return `## Why
Patchline found ${view.findings.length} known vulnerabilit${view.findings.length === 1 ? "y" : "ies"} in \`${ctx.repo}\` (risk class **${ctx.riskClass}**).${ctx.incidentUrl ? ` Tracking incident: ${ctx.incidentUrl}` : ""}

## Findings (scanner data, triage by ${view.models.get("triage") ?? "n/a"})
| Advisory | Package | Version | Severity | Reachability (VEX) |
|---|---|---|---|---|
${findings}

## Validation (measured, never model-reported)
| | Check | Detail |
|---|---|---|
${checks}

## Dependency changes
${changes}

\`\`\`
${view.diffStat.trim()}
\`\`\`

## What the agent changed (${view.models.get("remediate") ?? "n/a"})
${view.summary || "no summary"}

## Independent review
${review}

## Gate decision
${decision}

<sub>Generated by Patchline. The model proposes the patch; the scanner, the checks above and \`.patchline/policy.json\` decide whether it ships.</sub>
`;
}
